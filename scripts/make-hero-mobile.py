"""Build the phone-sized hero that is inlined into the HTML (lib/hero-mobile.ts).

On phones the hero image is the Largest Contentful Paint. Inlining a ~6 KB portrait crop
as a data URI means it paints with the first frame instead of waiting on the network.
Re-run after changing public/hero/hero.webp:

    python3 scripts/make-hero-mobile.py
"""

import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public/hero/hero.webp"
OUT = ROOT / "lib/hero-mobile.ts"

ASPECT = 412 / 720  # the phone hero box (width / height)
FOCUS_X = 0.62  # same horizontal focus as the desktop object-position
WIDTH, QUALITY = 720, 55

im = Image.open(SRC).convert("RGB")
w, h = im.size
crop_w = round(h * ASPECT)
x0 = round((w - crop_w) * FOCUS_X)
crop = im.crop((x0, 0, x0 + crop_w, h)).resize((WIDTH, round(WIDTH / ASPECT)), Image.LANCZOS)

buf = io.BytesIO()
crop.save(buf, "WEBP", quality=QUALITY, method=6)
data = base64.b64encode(buf.getvalue()).decode()
OUT.write_text(
    "// Generated by scripts/make-hero-mobile.py — do not edit by hand.\n"
    f"export const HERO_MOBILE = {{ src: \"data:image/webp;base64,{data}\", width: {crop.width}, height: {crop.height} }};\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)} ({len(buf.getvalue()) // 1024} KB image, {len(data) // 1024} KB base64)")
